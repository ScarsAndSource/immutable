#!/usr/bin/env python3
"""Writes docs/POLICY.md from src/immutable/policy.py. Never edit POLICY.md by hand.

  python scripts/gen_policy_doc.py            # rewrite docs/POLICY.md
  python scripts/gen_policy_doc.py --check    # exit 1 if it differs from the code

Adding an event type to policy.py without a plain-language line in DESC below is an
error on purpose: the policy page must say what each event is.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from immutable import policy  # noqa: E402

OUT = ROOT / "docs" / "POLICY.md"

DESC = {
    "SESSION_START": "A session opened. Records the hash of the exam paper, the hash of the roster and the agent version.",
    "BOOT": "The agent started, or resumed after a restart.",
    "FILE_SAVE": "A file in the workspace changed. Records its path, its SHA-256 and its size. Never its contents.",
    "RUN_START": "The student ran a file. Records the path and hash of the file that ran.",
    "RUN_END": "The run finished. Records the exit code, the duration and the hash of the output. Never the output.",
    "SUBMIT": "Final submission. Records the hash of the file manifest and the number of files.",
    "CHECKPOINT": "A Merkle root over earlier events, so a long log can be checked quickly.",
    "HEARTBEAT": "A sign of life. Carries no data.",
    "RECOVERY": "The agent restarted after a power cut or crash. Records the last good event and how many bytes were discarded.",
    "TRANSFER": "An assessor-signed move of the student to a different seat. Records the old seat, its last event and head, and the assessor's signature.",
    "SESSION_END": "The session closed: submitted, timed out or aborted.",
}

KIND = {
    "is_hash": "a SHA-256 hash (64 hex characters)",
    "_relpath": "a relative file path inside the workspace",
    "_uint": "a non-negative whole number",
    "_sint": "a whole number",
    "_ident": "a short identifier (letters, digits, . _ -)",
    "_short": "a short printable ASCII label (up to 32 characters)",
    "_sig": "an Ed25519 signature (128 hex characters)",
}

NEVER = [
    "keystrokes or typing rhythm", "screen contents or screenshots", "camera images or video",
    "microphone audio", "biometrics of any kind", "the clipboard", "window titles or the list of open programs",
    "browsing history or network traffic", "file contents between saves (only hashes)",
    "the text a program printed (only its hash)",
]


def kind(fn) -> str:
    name = getattr(fn, "__name__", "")
    if name in KIND:
        return KIND[name]
    cells = getattr(fn, "__closure__", None)
    if name == "<lambda>" and cells:
        return "one of: " + ", ".join(f"`{v}`" for v in cells[0].cell_contents)
    raise SystemExit(f"policy field check {name!r} has no description in KIND; add one")


def render() -> str:
    missing = sorted(set(policy.SCHEMAS) - set(DESC))
    if missing:
        raise SystemExit(f"event types without a description in DESC: {missing}")
    out = [
        "# What Immutable records",
        "",
        "<!-- Generated by scripts/gen_policy_doc.py from src/immutable/policy.py. Do not edit. -->",
        "",
        "Immutable records fingerprints and coarse milestones. The list below is the whole list:",
        "an event type that is not here cannot exist, and a field that is not listed for its type",
        "cannot be carried. There is no free-text field.",
        "",
        "## Never recorded",
        "",
    ]
    out += [f"- {n}" for n in NEVER]
    out += ["", "No event type or field above can carry any of these, which is why the guarantee holds.",
            "", "## Every event also carries bookkeeping", "",
            "Which exam, session and seat it belongs to, its position in the chain, the boot it",
            "happened in, this computer's clock readings, and the hash of the event before it.",
            "", "## Event types", ""]
    for etype, schema in policy.SCHEMAS.items():
        out += [f"### {etype}", "", DESC[etype], ""]
        if schema:
            out += ["| Field | Allowed value |", "|---|---|"]
            out += [f"| `{f}` | {kind(fn)} |" for f, fn in schema.items()]
        else:
            out += ["No fields."]
        out += [""]
    out += ["## Things to know", "",
            "- File **names** are recorded (paths relative to the workspace). Name files accordingly.",
            "- Contents of submitted files are kept at submission, so they can be marked and disputes settled.",
            "- Candidates appear under a pseudonymous ID from the roster, never a real name.", ""]
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("docs/POLICY.md matches the code" if ok else "docs/POLICY.md is out of date: run scripts/gen_policy_doc.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
